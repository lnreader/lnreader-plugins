  async popularNovels(
    pageNo: number,
    {
      showLatestNovels,
      filters,
    }: Plugin.PopularNovelsOptions<typeof this.filters>,
  ): Promise<Plugin.NovelItem[]> {
    const params = new URLSearchParams({ page: pageNo.toString() });
    const sort = showLatestNovels
      ? 'updated'
      : filters?.sort?.value || 'popular';

    if (sort !== 'updated') params.set('sort', sort);
    filters?.country?.value?.forEach(country =>
      params.append('country', country),
    );
    filters?.tags?.value?.include?.forEach(tag => params.append('tag', tag));
    filters?.events?.value?.include?.forEach(event =>
      params.append('event', event),
    );
    if (filters?.status?.value) params.append('status', filters.status.value);

    const result: CatalogResponse = await fetchApi(
      `${this.site}/api/catalog?${params.toString()}`,
    ).then(res => res.json());

    return result.items.map(novel => ({
      name: novel.title || novel.originalTitle,
      cover: this.resolveUrl(novel.posterUrl),
      path: `${novel.id}-${novel.slug}`,
    }));
  }

  async parseNovel(novelPath: string): Promise<Plugin.SourceNovel> {
    const id = novelPath.split('-', 1)[0];
    const page = await fetchApi(this.resolveUrl(novelPath)).then(res =>
      res.text(),
    );
    const title = /<h1[^>]*>([\s\S]*?)<\/h1>/
      .exec(page)?.[1]
      .replace(/<[^>]+>/g, '')
      .trim();
    const summary =
      /<div[^>]+id="book-description"[^>]*>([\s\S]*?)<\/div>/
        .exec(page)?.[1]
        .replace(/<[^>]+>/g, '')
        .trim() || '';
    const coverPath = /<img[^>]+src="\/_next\/image\?url=([^"&]+)/.exec(
      page,
    )?.[1];
    const cover = coverPath
      ? this.resolveUrl(decodeURIComponent(coverPath))
      : defaultCover;
    const author = /book-author-byline[\s\S]*?<strong[^>]*>([\s\S]*?)<\/strong>/
      .exec(page)?.[1]
      .replace(/<[^>]+>/g, '')
      .trim();

    let genres = '';
    const genresMatch = /\\"genres\\":(\[.*?\]),\\"labels\\":/.exec(page);
    if (genresMatch) {
      try {
        genres = (JSON.parse(genresMatch[1].replace(/\\"/g, '"')) as Genre[])
          .map(g => g.title)
          .join(', ');
      } catch {
        // ignore malformed payload
      }
    }

    const statusId =
      /book-kicker-status"[^>]*href="\/ranobe\?status=(\d+)"/.exec(page)?.[1];

    const novel: Plugin.SourceNovel = {
      path: novelPath,
      name: title || '',
      cover,
      summary,
      author: author || '',
      genres: genres || undefined,
      status: statusId
        ? statusKey[Number(statusId)] || NovelStatus.Unknown
        : undefined,
    };

    const first: ChaptersResponse = await fetchApi(
      `${this.site}/api/books/${id}/chapters?limit=${CHUNK_SIZE}&offset=0`,
    ).then(res => res.json());

    const offsets: number[] = [];
    for (let offset = CHUNK_SIZE; offset < first.total; offset += CHUNK_SIZE) {
      offsets.push(offset);
    }
    const rest: ChaptersResponse[] = await Promise.all(
      offsets.map(offset =>
        fetchApi(
          `${this.site}/api/books/${id}/chapters?limit=${CHUNK_SIZE}&offset=${offset}`,
        ).then(res => res.json()),
      ),
    );
    const items = [first.items, ...rest.map(r => r.items)].flat();

    novel.chapters = items.map((chapter, index) => ({
      name: chapter.title,
      path: `${novelPath}/chapter/${chapter.id}`,
      releaseTime: dayjs(chapter.changedAt).format('LLL'),
      chapterNumber: index + 1,
    }));
    return novel;
  }

  async parseChapter(chapterPath: string): Promise<string> {
    const id = chapterPath.split('/').pop();
    const { chapter }: ChapterResponse = await fetchApi(
      `${this.site}/api/chapters/${id}`,
    ).then(res => res.json());
    return chapter.html.replace(
      /src="\/(api\/media\/[^"]*)"/g,
      `src="${this.site}/$1"`,
    );
  }

